import type { Graph } from "./types";

type E = [string, string, number?];
function g(directed: boolean, nodes: [string, number, number][], edges: E[]): Graph {
  return {
    directed,
    nodes: nodes.map(([id, x, y]) => ({ id, x, y })),
    edges: edges.map(([from, to, w]) => (w === undefined ? { from, to } : { from, to, w })),
  };
}

function petersen(): Graph {
  const nodes: [string, number, number][] = [];
  for (let i = 0; i < 5; i++) {
    const a = (2 * Math.PI * i) / 5 - Math.PI / 2;
    nodes.push([String(i + 1), 5 + 4.5 * Math.cos(a), 5 + 4.5 * Math.sin(a)]);
  }
  for (let i = 0; i < 5; i++) {
    const a = (2 * Math.PI * i) / 5 - Math.PI / 2;
    nodes.push([String(i + 6), 5 + 2 * Math.cos(a), 5 + 2 * Math.sin(a)]);
  }
  const edges: E[] = [];
  for (let i = 0; i < 5; i++) {
    edges.push([String(i + 1), String(((i + 1) % 5) + 1)]);
    edges.push([String(i + 1), String(i + 6)]);
    edges.push([String(i + 6), String(((i + 2) % 5) + 6)]);
  }
  return g(false, nodes, edges);
}

