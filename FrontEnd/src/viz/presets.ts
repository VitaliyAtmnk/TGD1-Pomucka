function complete(n: number): Graph {
  const nodes: [string, number, number][] = [];
  for (let i = 0; i < n; i++) {
    const a = (2 * Math.PI * i) / n - Math.PI / 2;
    nodes.push([String(i + 1), 5 + 4.5 * Math.cos(a), 5 + 4.5 * Math.sin(a)]);
  }
  const edges: E[] = [];
  for (let i = 1; i <= n; i++) for (let j = i + 1; j <= n; j++) edges.push([String(i), String(j)]);
  return g(false, nodes, edges);
}
